#!/usr/bin/env python3

import argparse
import csv
import filecmp
import shutil
from pathlib import Path


def archive_tasks(task_file, dry_run=False):
    task_file = Path(task_file)

    if not task_file.exists():
        raise FileNotFoundError(f"Task file does not exist: {task_file}")

    results = []

    with open(task_file, newline="") as f:
        reader = csv.DictReader(f)
        required = {"dataset_id", "mapfile", "archive_path"}
        missing = required - set(reader.fieldnames or [])

        if missing:
            raise ValueError(
                f"Missing required columns: {', '.join(sorted(missing))}"
            )

        for row in reader:
            dataset_id = row["dataset_id"]
            source = Path(row["mapfile"])
            destination = Path(row["archive_path"])

            result = {
                "dataset_id": dataset_id,
                "mapfile": str(source),
                "archive_path": str(destination),
                "status": None,
                "error_message": "",
            }

            try:
                if not source.exists():
                    raise FileNotFoundError(
                        f"Source mapfile does not exist: {source}"
                    )

                if destination.exists():
                    if filecmp.cmp(source, destination, shallow=False):
                        result["status"] = "ALREADY_EXISTS"
                        print(f"ALREADY EXISTS {dataset_id}")
                    else:
                        result["status"] = "CONFLICT"
                        result["error_message"] = (
                            "Destination exists but differs from source"
                        )
                        print(
                            f"CONFLICT {dataset_id}: "
                            "destination differs from source"
                        )
                elif dry_run:
                    result["status"] = "WOULD_ARCHIVE"
                    print(f"DRY RUN ARCHIVE {dataset_id}")
                    print(f"  Source:      {source}")
                    print(f"  Destination: {destination}")
                else:
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copy2(source, destination)
                    result["status"] = "SUCCESS"
                    print(f"ARCHIVED {dataset_id}")

            except Exception as exc:
                result["status"] = "FAILED"
                result["error_message"] = str(exc)
                print(f"FAILED {dataset_id}: {exc}")

            results.append(result)

    return results


def main():
    parser = argparse.ArgumentParser(
        description="Execute ESGF archive tasks."
    )
    parser.add_argument(
        "task_file",
        help="CSV file generated by pubflow archive",
    )
    parser.add_argument(
        "--results",
        default="archive_results.csv",
        help="Output CSV for archive results",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Show what would be archived without copying files",
    )

    args = parser.parse_args()
    results = archive_tasks(args.task_file, dry_run=args.dry_run)

    with open(args.results, "w", newline="") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "dataset_id",
                "mapfile",
                "archive_path",
                "status",
                "error_message",
            ],
        )
        writer.writeheader()
        writer.writerows(results)

    counts = {
        "WOULD_ARCHIVE": sum(r["status"] == "WOULD_ARCHIVE" for r in results),
        "SUCCESS": sum(r["status"] == "SUCCESS" for r in results),
        "ALREADY_EXISTS": sum(
            r["status"] == "ALREADY_EXISTS" for r in results
        ),
        "CONFLICT": sum(r["status"] == "CONFLICT" for r in results),
        "FAILED": sum(r["status"] == "FAILED" for r in results),
    }

    print()

    if args.dry_run:
        print(
            f"Dry run completed: "
            f"{counts['WOULD_ARCHIVE']} would archive, "
            f"{counts['ALREADY_EXISTS']} already existed, "
            f"{counts['CONFLICT']} conflicts, "
            f"{counts['FAILED']} failed"
        )
    else:
        print(
            f"Completed: "
            f"{counts['SUCCESS']} succeeded, "
            f"{counts['ALREADY_EXISTS']} already existed, "
            f"{counts['CONFLICT']} conflicts, "
            f"{counts['FAILED']} failed"
        )


if __name__ == "__main__":
    main()