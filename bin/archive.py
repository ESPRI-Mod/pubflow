#!/usr/bin/env python3

import csv
import shutil
from pathlib import Path
import argparse


def archive_tasks(task_file):
    task_file = Path(task_file)

    if not task_file.exists():
        raise FileNotFoundError(
            f"Task file does not exist: {task_file}"
        )

    results = []

    with open(task_file, newline="") as f:
        reader = csv.DictReader(f)

        required = {
            "dataset_id",
            "mapfile",
            "archive_path",
        }

        missing = required - set(reader.fieldnames or [])

        if missing:
            raise ValueError(
                f"Missing required columns: {', '.join(sorted(missing))}"
            )

        for row in reader:
            dataset_id = row["dataset_id"]
            source = Path(row["mapfile"])
            destination = Path(row["archive_path"])

            result = {
                "dataset_id": dataset_id,
                "mapfile": str(source),
                "archive_path": str(destination),
                "status": None,
                "error_message": "",
            }

            try:
                if not source.exists():
                    raise FileNotFoundError(
                        f"Source mapfile does not exist: {source}"
                    )

                destination.parent.mkdir(
                    parents=True,
                    exist_ok=True,
                )

                shutil.copy2(
                    source,
                    destination,
                )

                result["status"] = "SUCCESS"

                print(
                    f"ARCHIVED {dataset_id}"
                )

            except Exception as exc:
                result["status"] = "FAILED"
                result["error_message"] = str(exc)

                print(
                    f"FAILED {dataset_id}: {exc}"
                )

            results.append(result)

    return results


def main():
    parser = argparse.ArgumentParser(
        description="Execute ESGF archive tasks."
    )

    parser.add_argument(
        "task_file",
        help="CSV file generated by pubflow archive",
    )
    parser.add_argument(
        "--results",
        default="archive_results.csv",
        help="Output CSV for archive results",
    )
    args = parser.parse_args()
    results = archive_tasks(args.task_file)
    with open(
            args.results,
            "w",
            newline="",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "dataset_id",
                "mapfile",
                "archive_path",
                "status",
                "error_message",
            ],
        )

        writer.writeheader()
        writer.writerows(results)

    successful = sum(
        r["status"] == "SUCCESS"
        for r in results
    )

    failed = sum(
        r["status"] == "FAILED"
        for r in results
    )

    print()
    print(
        f"Completed: {successful} succeeded, {failed} failed"
    )


if __name__ == "__main__":
    main()